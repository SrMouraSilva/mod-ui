#!/usr/bin/env python3
"""Regenerates every diagram of docs/modui-client.md: one SVG per diagram plus index.html (a gallery that shows them).

    python3 docs/modui-client/diagrams/src/build.py            # writes ../*.svg and ../index.html
    python3 docs/modui-client/diagrams/src/build.py --check    # only draws and prints geometry warnings, writes nothing

Needs only the Python 3 standard library. The diagrams themselves are defined in specs.py; see ../README.md.
"""
import html
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import specs  # noqa: E402
from engine import render_svg  # noqa: E402

OUT = HERE.parent

INDEX = '''<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>modui-client diagrams</title>
  <link href="https://fonts.googleapis.com/css2?family=Instrument+Serif:ital@0;1&family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500;600&display=swap" rel="stylesheet">
  <style>
    *, *::before, *::after {{ box-sizing: border-box; margin: 0; padding: 0; }}
    body {{ font-family: 'Geist', system-ui, sans-serif; background: #f5f5f5; color: #2e1f33; padding: 3rem 2rem; }}
    .frame {{ max-width: 1100px; margin: 0 auto; }}
    .note {{ font-size: 0.85rem; color: #5c4a64; margin-bottom: 3rem; max-width: 60ch; }}
    .eyebrow {{ font-family: 'Geist Mono', ui-monospace, monospace; font-size: 0.66rem; letter-spacing: 0.18em; text-transform: uppercase; color: #5c4a64; margin-bottom: 0.5rem; }}
    h1 {{ font-family: 'Instrument Serif', serif; font-size: clamp(1.5rem, 2.4vw + 0.75rem, 2rem); font-weight: 400; letter-spacing: -0.02em; line-height: 1.15; margin-bottom: 1.5rem; }}
    section {{ margin-bottom: 4rem; }}
    .diagram-container {{ width: 100%; overflow-x: auto; }}
    object {{ display: block; width: 100%; }}
    @media print {{ .diagram-container {{ overflow-x: visible; }} object {{ min-width: 0 !important; }} }}
  </style>
</head>
<body>
  <div class="frame">
    <p class="note">Generated by <code>src/build.py</code> from <code>src/specs.py</code>. Every diagram is the SVG next to this file; this page only shows them (with the web fonts).</p>
{sections}
  </div>
</body>
</html>
'''


def main():
    check_only = '--check' in sys.argv
    sections = []
    for make in specs.SPECS:
        d = make()
        svg, w, h = render_svg(d)
        print(f"{d['slug']}: {w}x{h}")
        if check_only:
            continue
        (OUT / f"{d['slug']}.svg").write_text(svg + '\n', encoding='utf-8')
        sections.append(
            f'    <section id="{d["slug"]}">\n      <p class="eyebrow">{html.escape(d["eyebrow"])}</p>\n      <h1>{html.escape(d["h1"])}</h1>\n'
            f'      <div class="diagram-container"><object type="image/svg+xml" data="{d["slug"]}.svg" style="min-width:{w}px;aspect-ratio:{w}/{h}" '
            f'aria-label="{html.escape(d["title"])}"></object></div>\n    </section>')
    if not check_only:
        (OUT / 'index.html').write_text(INDEX.format(sections='\n'.join(sections)), encoding='utf-8')


if __name__ == '__main__':
    main()
